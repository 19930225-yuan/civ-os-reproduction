# -*- coding: utf-8 -*-
"""实测七/八：编码表算术一致性审计 + 全表蒙特卡洛敏感性"""
import csv, random
random.seed(7)
OUT = "/home/work/.openclaw/workspace/实测数据"
cases = ["犹太","中华","日本","基督教","印度","伊斯兰","拜占庭","古埃及"]

# ===== 编码表原始数据（据补充材料表A2/A5/A11/A13/A14） =====
cond1_sub = {  # 1a,1b,1c,1d,1e
 "犹太":[1,1,.5,1,1], "中华":[.5,.5,0,.5,1], "日本":[0,.5,.5,1,.5], "基督教":[1,1,1,1,0],
 "印度":[.5,1,1,1,.5], "伊斯兰":[1,1,1,1,1], "拜占庭":[.5,.5,1,.5,.5], "古埃及":[0,.5,1,.5,.5]}
cond1_tot = {"犹太":4.5,"中华":2.5,"日本":1.5,"基督教":4.5,"印度":4.0,"伊斯兰":5.0,"拜占庭":2.5,"古埃及":2.5}
cond2_sub = {
 "犹太":[1,1,1,1,.5], "中华":[1,1,1,1,.5], "日本":[.5,.5,.5,.5,.5], "基督教":[.5,0,0,.5,1],
 "印度":[1,1,1,1,0], "伊斯兰":[.5,.5,.5,.5,.5], "拜占庭":[.5,.5,.5,0,.5], "古埃及":[.5,0,.5,.5,.5]}
cond2_tot = {"犹太":4.5,"中华":4.5,"日本":2.5,"基督教":2.0,"印度":3.0,"伊斯兰":2.5,"拜占庭":1.0,"古埃及":2.0}
cond4_sub = {  # (微五项, 微总, 宏五项, 宏总, 组织总分)
 "犹太":([.5,.5,.5,.5,0],2.0,[0,0,0,0,0],0,2.0),
 "中华":([.5,.5,.5,.5,.5],2.5,[.5,.5,.5,.5,0],2.5,5.0),
 "日本":([.5,.5,.5,.5,.5],2.5,[.5,.5,.5,0,0],2.0,4.5),
 "基督教":([.5,.5,.5,.5,0],2.0,[.5,.5,.5,.5,.5],2.5,4.5),
 "印度":([.5,.5,.5,.5,.5],2.5,[0,0,0,0,0],1.0,3.5),   # 原表宏观栏误列为六项全0
 "伊斯兰":([.5,.5,.5,.5,.5],2.5,[.5,.5,.5,0,0],2.0,4.5),
 "拜占庭":([0,0,0,0,0],0.5,[.5,.5,.5,0,.5],2.0,2.5),  # 原表微观栏误列为六项全0
 "古埃及":([0,0,0,0,0],0.5,[.5,.5,.5,.5,.5],2.5,3.0)} # 原表微观栏误列为六项全0
cond5_sub = {
 "犹太":[1,1,1,1,1], "中华":[1,1,1,1,.5], "日本":[1,1,1,1,1], "基督教":[.5,.5,1,1,.5],
 "印度":[.5,.5,1,1,.5], "伊斯兰":[0,.5,.5,.5,.5], "拜占庭":[0,0,.5,.5,0], "古埃及":[0,0,0,0,0]}
cond5_tot = {"犹太":5.0,"中华":4.5,"日本":5.0,"基督教":3.5,"印度":3.5,"伊斯兰":2.0,"拜占庭":1.0,"古埃及":0}
tot = {  # 表A14/表6 公布总分
 "犹太":[4.5,4.5,4.25,2.0,5.0], "中华":[2.5,4.5,4.5,5.0,4.5], "日本":[1.5,2.5,4.0,4.5,5.0],
 "基督教":[4.5,2.0,2.75,4.5,3.5], "印度":[4.0,3.0,3.5,3.5,3.5], "伊斯兰":[5.0,2.5,3.5,4.5,2.0],
 "拜占庭":[2.5,1.0,2.25,2.5,1.0], "古埃及":[2.5,2.0,1.75,3.0,0]}
ge4_pub = {"犹太":4,"中华":4,"日本":3,"基督教":3,"印度":1,"伊斯兰":2,"拜占庭":0,"古埃及":0}

print("== 实测七：编码表算术一致性审计 ==")
issues = []
for c in cases:
    s = sum(cond1_sub[c])
    if abs(s - cond1_tot[c]) > 1e-9:
        issues.append((c, "条件一", f"子维度和{s:.1f} ≠ 总分{cond1_tot[c]}（差{s-cond1_tot[c]:+.1f}）"))
    s = sum(cond2_sub[c])
    if abs(s - cond2_tot[c]) > 1e-9:
        issues.append((c, "条件二", f"子维度和{s:.1f} ≠ 总分{cond2_tot[c]}（差{s-cond2_tot[c]:+.1f}）"))
    mi, mt, ma, mat, org = cond4_sub[c]
    if abs(sum(mi) - mt) > 1e-9:
        issues.append((c, "条件四·微观", f"子维度和{sum(mi):.1f} ≠ 微总{mt}（差{sum(mi)-mt:+.1f}）"))
    if abs(sum(ma) - mat) > 1e-9:
        issues.append((c, "条件四·宏观", f"子维度和{sum(ma):.1f} ≠ 宏总{mat}（差{sum(ma)-mat:+.1f}）"))
    if abs(mt + mat - org) > 1e-9:
        issues.append((c, "条件四·组织", f"微总+宏总={mt+mat:.1f} ≠ 组织总分{org}"))
    s = sum(cond5_sub[c])
    if abs(s - cond5_tot[c]) > 1e-9:
        issues.append((c, "条件五", f"子维度和{s:.1f} ≠ 总分{cond5_tot[c]}"))
    ge4 = sum(1 for v in tot[c] if v >= 4)
    if ge4 != ge4_pub[c]:
        issues.append((c, "表A14/表6", f"≥4条件数实为{ge4}，表中记为{ge4_pub[c]}"))
# 苏美尔（补充材料表B1）
sumer = sum([0,.5,.5,.5,.5])
if abs(sumer - 1.5) > 1e-9:
    issues.append(("苏美尔(表B1)", "条件一", f"子维度和{sumer:.1f} ≠ 公布1.5（差{sumer-1.5:+.1f}）"))
for row in issues:
    print("  ⚠", " | ".join(map(str, row)))
print(f"  合计不一致 {len(issues)} 处；条件五（核心自变量）全部自洽 ✓")
with open(f"{OUT}/study7_编码表审计.csv", "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f); w.writerow(["案例","项目","问题"]); w.writerows(issues)

# ===== 实测八：蒙特卡洛敏感性（40个评分 ±0.5） =====
print("\n== 实测八：全表蒙特卡洛敏感性（10000次，±0.5，p=0.25/0.5/0.25） ==")
outcome = {"犹太":1,"中华":1,"日本":1,"基督教":1,"印度":1,"伊斯兰":1,"拜占庭":0,"古埃及":0}  # 政权崩溃后是否恢复独立宏观组织（日本/基督教等取其历史判定）
tested = {"犹太","中华","印度","拜占庭","古埃及"}  # 经历完整压力测试的案例
def perturb(v):
    d = random.choice([-0.5, 0, 0.5])
    return min(5.0, max(0.0, v + d))
hold_f1 = hold_thr = hold_ge4 = hold_contrast = 0
N = 10000
for _ in range(N):
    P = {c: [perturb(v) for v in tot[c]] for c in cases}
    # F1 未触发：拜占庭、古埃及的≥4条件数保持0
    if sum(1 for v in P["拜占庭"] if v >= 4) == 0 and sum(1 for v in P["古埃及"] if v >= 4) == 0:
        hold_f1 += 1
    # 阈值律：{外壳≤1.0} ⊆ {未恢复} 且 {已恢复} ⊆ {外壳>1.0}
    ok = all(not (P[c][4] <= 1.0) or outcome[c] == 0 for c in tested) and \
         all(not (outcome[c] == 1) or P[c][4] > 1.0 for c in tested)
    if ok: hold_thr += 1
    # ≥4数列不变（按修正后取值）
    if all(sum(1 for v in P[c] if v >= 4) == sum(1 for v in tot[c] if v >= 4) for c in cases):
        hold_ge4 += 1
    # 关键对比：犹太外壳>古埃及外壳；古埃及组织>犹太组织；中华组织>犹太组织；犹太信仰>中华信仰
    if (P["犹太"][4] > P["古埃及"][4] and P["古埃及"][3] > P["犹太"][3]
            and P["中华"][3] > P["犹太"][3] and P["犹太"][0] > P["中华"][0]):
        hold_contrast += 1
print(f"  F1'未触发'状态保持率: {hold_f1/N:.1%}")
print(f"  阈值律对应关系保持率: {hold_thr/N:.1%}")
print(f"  '≥4条件数'列完全不变概率: {hold_ge4/N:.1%}  ← 最敏感")
print(f"  §2.2关键对比（对比A/B/C）保持率: {hold_contrast/N:.1%}")
print("\n  结论：核心结论（阈值律、F1状态、对比A/B/C）对±0.5扰动稳健；'≥4条件数'计数列对4.0/3.5边界值敏感——该列宜作描述性辅助，不承担论证功能（与论文§2.2'加总不承担互补效能判定'的声明一致）。")
